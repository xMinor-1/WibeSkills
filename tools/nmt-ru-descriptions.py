def replace_description(text: str, new_description: str) -> str:
    lines = text.splitlines(keepends=True)
    if not lines or lines[0].strip() != "---":
        raise ValueError("нет frontmatter")

    end = next(i for i, line in enumerate(lines[1:], start=1) if line.strip() == "---")
    start = next(i for i in range(1, end) if lines[i].startswith("description:"))

    # конец блока description — следующая строка frontmatter без отступа
    stop = next((i for i in range(start + 1, end) if lines[i][:1] not in (" ", "\t")), end)

    # break_on_hyphens=False — иначе перенос рвёт имена скиллов (nmt-craft-value-proposition)
    body = textwrap.fill(
        new_description,
        width=98,
        initial_indent="  ",
        subsequent_indent="  ",
        break_on_hyphens=False,
        break_long_words=False,
    )
    block = "description: >-\n" + body + "\n"
    return "".join(lines[:start]) + block + "".join(lines[stop:])


def main() -> int:
    if not SKILLS_DIR.is_dir():
        print(f"нет папки скиллов: {SKILLS_DIR}", file=sys.stderr)
        return 1

    changed = 0
    for name, description in DESCRIPTIONS.items():
        path = SKILLS_DIR / name / "SKILL.md"
        if not path.exists():
            print(f"пропущен (нет файла): {name}", file=sys.stderr)
            continue
        text = path.read_text(encoding="utf-8")
        updated = replace_description(text, description)
        if updated != text:
            path.write_text(updated, encoding="utf-8")
            changed += 1
            print(f"обновлён: {name}")
        else:
            print(f"уже на русском: {name}")

    missing = {p.name for p in SKILLS_DIR.iterdir() if p.is_dir()} - set(DESCRIPTIONS)
    if missing:
        print(f"\nбез перевода (появились в новой версии канона): {', '.join(sorted(missing))}")
    print(f"\nизменено файлов: {changed}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
