export const meta = {
  name: 'helpx5-prod-update',
  description: 'Дополняет статьи боевой базы help-центра веб-путём из материалов ЛК ТРК',
  whenToUse: 'Когда целевая база — прод X5, а материалы описывают веб-кабинет',
  phases: [
    { title: 'Дополнение', detail: 'по агенту на прод-статью: добавить раздел второго интерфейса' },
    { title: 'Сверка', detail: 'по агенту на статью: не переписан ли прод-текст, верны ли факты' },
  ],
}

// args = { group: 'A-rejsy', items: [{slug, documentId, category, title}], kb, skill, help }
const A = typeof args === 'string' ? JSON.parse(args) : (args || {})
const KB = A.kb || '/home/coder/Work/3. projects/x5transport/Продукты/Сайт х5т/Help-центр/knowledge-base'
const SKILL = A.skill || '/home/coder/Work/3. projects/WibeSkills/skills/helpx5'
const ITEMS = A.items || []
const GROUP = A.group || 'группа'

if (!ITEMS.length) {
  log('Статей не передано.')
  return { error: 'empty items' }
}

const RESULT_SCHEMA = {
  type: 'object',
  required: ['slug', 'status'],
  properties: {
    slug: { type: 'string' },
    status: { type: 'string', description: 'done | skipped — если веб-пути в материалах нет' },
    added: { type: 'string', description: 'что добавлено в статью' },
    media: { type: 'array', items: { type: 'string' } },
    sources: {
      type: 'array',
      items: {
        type: 'object',
        required: ['material'],
        properties: { material: { type: 'string' }, locator: { type: 'string' } },
      },
    },
    discrepancies: {
      type: 'array',
      description: 'где материалы противоречат прод-тексту — НЕ править, только зафиксировать',
      items: { type: 'string' },
    },
    gaps: { type: 'array', description: 'чего не хватило в материалах', items: { type: 'string' } },
  },
}

const VERIFY_SCHEMA = {
  type: 'object',
  required: ['slug', 'verdict'],
  properties: {
    slug: { type: 'string' },
    verdict: { type: 'string', description: 'ok | fixed | blocked' },
    issues: { type: 'array', items: { type: 'string' } },
    prod_text_touched: { type: 'boolean', description: 'был ли изменён исходный прод-текст по смыслу' },
  },
}

const RULES = `
ЦЕЛЕВАЯ БАЗА — ПРОД X5, а не наш стенд. Эталон существующих текстов: ${KB}/prod/articles/<слаг>.md
(их трогать нельзя, это снимок). Рабочая копия, которую ты правишь: ${KB}/prod-update/articles/<слаг>.md

ПРАВИЛО СТРУКТУРЫ (решение владельца):
одна статья = одна задача пользователя, два интерфейса внутри неё.
- Веб-кабинет ЛК ТРК — раздел «## Веб-ЛК», мобильное приложение — «## Приложение».
  Писать ровно так: это ключи табов из конвенции ${A.help || KB + '/..'}/md-format.md.
- Блок «> **Коротко:**» остаётся ПЕРВЫМ, до заголовков платформ, и должен быть верен для обоих
  интерфейсов. Если он верен только для приложения — переформулируй так, чтобы был верен для обоих.
- Если в прод-статье НЕТ заголовков платформ, а её текст описывает приложение — оберни имеющееся
  содержимое в «## Приложение», НИЧЕГО не меняя по смыслу, и добавь «## Веб-ЛК» рядом.
- Если в прод-статье уже есть «## Веб-ЛК» — дополняй его, а не создавай второй такой заголовок.
- Если материалы описывают только веб-путь, а приложения по этой задаче нет — раздел «## Приложение»
  НЕ выдумывать.

ЧТО НЕЛЬЗЯ:
- удалять или переписывать по смыслу существующий прод-текст (только дополнять и оборачивать);
- заводить новые категории — категория остаётся та, что в прод-статье;
- додумывать факты, которых нет в материалах;
- молча править расхождения: если материал противоречит прод-тексту (другая кнопка, срок, экран) —
  ОСТАВЬ прод-формулировку и запиши расхождение в discrepancies.

ССЫЛКИ: в проде внутренние ссылки абсолютные — https://x5transport.ru/help/article/<слаг>.
Новые ссылки ставить в том же виде и только на слаги, которые есть в ${KB}/prod/manifest.json.

КАРТИНКИ: класть в ${KB}/prod-update/media/<слаг>/, в тексте ссылаться коротким именем файла.
Брать из материалов; кадры видео — только читаемые.

ИСТОЧНИКИ (в порядке приоритета):
1. ${KB}/digests/333b34949d8766fe42f5e032ed896543.json — разбор полной выгрузки вики: 49 тем
   с указанием, где лежит фактура. Прочитай его перед работой и найди свою тему.
2. /home/coder/helpx5-cache/extracted/333b34949d8766fe42f5e032ed896543/ — сами документы.
3. ${KB}/articles/<слаг>.md — статьи, написанные в этом же прогоне под наш стенд: там уже
   разобранная фактура по веб-кабинету, её можно переносить, приводя к структуре прод-статьи.
4. Видео: /home/coder/helpx5-cache/video/<md5>/ — transcript.md и frames/ (кадры смотреть глазами).

СВЕЖЕСТЬ ИСТОЧНИКОВ: страницы ЛК ТРК 1–6 и тендеры выгружены в январе 2025, скриншоты там
2022–2023 годов и старая навигация — оттуда берём ЛОГИКУ процесса, но НЕ экраны и НЕ названия
разделов. Свежие блоки (Предоплата, Инвойс Дискаунтинг, Бизнес-счёт, Поиск грузов) — май-август
2026, их берём целиком со скриншотами.

ЧЕТЫРЕ ИЗВЕСТНЫХ РАСХОЖДЕНИЯ — не решать самостоятельно, оставить прод-формулировку и внести
в discrepancies (владелец сверит с продуктом):
- типы рейсов для предоплаты: прод «Коммерция или МФП Экспедиция» против МФП/ВФП по четыре типа;
- срок доступности предоплаты: «пока не выставлен УПД» / «менее 15 дней с последней погрузки» /
  «кнопка скрывается после формирования УПД»;
- куда приходят деньги: «на Бизнес-счёт» (прод) против «на расчётный счёт на следующий рабочий день»;
- подтверждение заявки на предоплату: в приложении окно «Заявка на предоплату» и кнопка
  «Подтвердить», в вебе — «Отправка заявки на предоплату» и кнопка «Подписать». Это РАЗНЫЕ
  интерфейсы — разнести по секциям, не переписывать одно другим.

Правила разметки и стиля — ${SKILL}/article-rules.md. Таблицы переносить markdown-таблицами
не шире 3 колонок; длинные списки статусов оформлять таблицей «Статус | Что означает».
`

phase('Дополнение')
const written = await pipeline(
  ITEMS,
  (it) =>
    agent(
      `Дополни статью боевой базы help-центра X5 «${it.title}» (слаг ${it.slug}, раздел ${it.category})
путём в веб-кабинете ЛК ТРК.

ПОРЯДОК:
1. Прочитай прод-версию: ${KB}/prod/articles/${it.slug}.md — это то, что сейчас видит пользователь.
2. Прочитай ${SKILL}/article-rules.md и правила ниже.
3. Найди в источниках фактуру по этой задаче для ВЕБ-кабинета.
4. Создай ${KB}/prod-update/articles/${it.slug}.md: прод-текст + добавленный раздел, по правилам ниже.
   Фронтматтер сохрани из прод-версии как есть и добавь строку cms_id: ${it.documentId}
5. Карточку связей запиши отдельным файлом ${KB}/prod-update/map.d/${it.slug}.json:
   {"sources": [{"material": "...", "locator": "..."}], "media": ["имя.png"],
    "change_reason": "добавлен путь в веб-кабинете", "discrepancies": ["..."]}
   Общий файл не трогать — агенты работают параллельно.

Если по этой задаче в материалах веб-пути нет вообще — не выдумывай: верни status=skipped
и объясни в gaps, чего не хватило. Пустую статью не создавай.

${RULES}`,
      { label: `веб:${it.slug.slice(0, 24)}`, phase: 'Дополнение', schema: RESULT_SCHEMA }
    ),
  (res, it) => {
    if (!res || res.status === 'skipped') return res
    return agent(
      `Сверь дополненную статью ${KB}/prod-update/articles/${it.slug}.md с её прод-версией
${KB}/prod/articles/${it.slug}.md.

Проверь по пунктам:
1. ИСХОДНЫЙ ПРОД-ТЕКСТ НЕ ИЗМЕНЁН ПО СМЫСЛУ. Допустимо: обёрнут в «## Приложение», поправлена
   разметка. Недопустимо: переписаны шаги, изменены названия кнопок, удалены абзацы, изменены
   ссылки. Сделай diff и проверь каждое отличие. Если прод-текст переписан — верни blocked
   и восстанови исходные формулировки.
2. Заголовки платформ ровно «## Веб-ЛК» и «## Приложение», второго такого же заголовка нет.
3. Блок «> **Коротко:**» первый и верен для обоих интерфейсов.
4. Фронтматтер сохранён из прод-версии, cms_id на месте и равен ${it.documentId}.
5. Ссылки абсолютные вида https://x5transport.ru/help/article/<слаг>, слаг существует
   в ${KB}/prod/manifest.json.
6. Картинки лежат в ${KB}/prod-update/media/${it.slug}/ и ссылки на них короткими именами.
7. Нет выдуманных фактов: каждое утверждение веб-раздела должно опираться на источник
   из карточки ${KB}/prod-update/map.d/${it.slug}.json.
8. Таблицы не шире 3 колонок.

Мелкие огрехи разметки и стиля чини сам. Смысловые проблемы — verdict=blocked с описанием.
Поле prod_text_touched=true, если исходный прод-текст был изменён по смыслу (это дефект).`,
      { label: `сверка:${it.slug.slice(0, 22)}`, phase: 'Сверка', schema: VERIFY_SCHEMA }
    ).then((v) => ({ ...res, verify: v }))
  }
)

const done = written.filter(Boolean)
return {
  group: GROUP,
  processed: done.length,
  skipped: done.filter((r) => r.status === 'skipped').map((r) => r.slug),
  blocked: done.filter((r) => r.verify?.verdict === 'blocked').map((r) => ({ slug: r.slug, issues: r.verify.issues })),
  prod_text_touched: done.filter((r) => r.verify?.prod_text_touched).map((r) => r.slug),
  discrepancies: done.flatMap((r) => (r.discrepancies || []).map((d) => `${r.slug}: ${d}`)),
  gaps: done.flatMap((r) => (r.gaps || []).map((g) => `${r.slug}: ${g}`)),
}
